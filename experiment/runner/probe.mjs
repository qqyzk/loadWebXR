#!/usr/bin/env node
/**
 * Offline probe of the initial view (desktop Chrome, Pixel 6 viewport).
 *
 * Opens each application's baseline experiment page (all assets are loaded
 * before the first frame) and, at the first frame, records:
 *   - the camera pose and projection;
 *   - the world-space bounding box of every model entity;
 *   - the VIA visibility score of every asset (Slocum et al., Web3D'21,
 *     mavens-lab/webxr_latency VIA.py): score = angle between the camera's view
 *     direction and the direction to the box centre (radians)
 *     + 2 * (box outside the view frustum ? 1 : 0); lower = requested earlier.
 *     VIA scores glTF primitives; our applications already consist of separate
 *     model files, so the score is computed per model entity and an asset takes
 *     the minimum over the entities that use it.
 *
 * Output: experiment/probe/<app>.json, used by gen_pages.py for the VIA request
 * order, the 4-level priority split and the visibility tracking of R1-1/R1-2.
 *
 * Usage: node probe.mjs [--apps tale,hallo,mus] [--viewport 915x412] [--out dir] [--headful]
 * (requires the pages generated by gen_pages.py)
 */
import fs from 'node:fs';
import path from 'node:path';
import { DEFAULT_CHROME, EXP_DIR, closeBrowser, loadPages, openBrowser, parseArgs, sleep, startServer, viewportFromString } from './lib.mjs';

const DEFAULTS = { apps: 'tale,hallo,mus', port: 8090, chrome: DEFAULT_CHROME, headful: false, settle: 1, viewport: '915x412', out: '' };

// Runs in the page after the first frame.
function inspectScene () {
  const THREE = AFRAME.THREE;
  const raw = (el, name) => Element.prototype.getAttribute.call(el, name);
  const scene = document.querySelector('a-scene');
  const cam = scene.camera;
  scene.object3D.updateMatrixWorld(true);
  cam.updateMatrixWorld(true);
  const frustum = new THREE.Frustum().setFromProjectionMatrix(
    new THREE.Matrix4().multiplyMatrices(cam.projectionMatrix, cam.matrixWorldInverse));
  const camPos = cam.getWorldPosition(new THREE.Vector3());
  const camDir = cam.getWorldDirection(new THREE.Vector3());

  const counts = {};
  const entities = [];
  for (const el of scene.querySelectorAll('a-gltf-model, [gltf-model]')) {
    const ref = raw(el, 'src') || raw(el, 'gltf-model') || '';
    const asset = ref.charAt(0) === '#' ? ref.slice(1) : ref;
    counts[asset] = (counts[asset] || 0) + 1;
    const mesh = el.getObject3D('mesh');
    const entry = { key: `${asset}#${counts[asset]}`, asset, visibleAttr: raw(el, 'visible'), hasMesh: !!mesh };
    if (mesh) {
      const box = new THREE.Box3().setFromObject(mesh);
      if (!box.isEmpty()) {
        const center = box.getCenter(new THREE.Vector3());
        const angle = camDir.angleTo(center.clone().sub(camPos));
        const inFrustum = frustum.intersectsBox(box);
        Object.assign(entry, {
          min: box.min.toArray(), max: box.max.toArray(), center: center.toArray(),
          distance: center.distanceTo(camPos), angle, inFrustum, viaScore: angle + 2 * (inFrustum ? 0 : 1)
        });
      }
    }
    entities.push(entry);
  }

  const assets = [];
  for (const item of document.querySelectorAll('a-assets > a-asset-item, a-assets > audio, a-assets > img')) {
    const ents = entities.filter((e) => e.asset === item.id && e.viaScore !== undefined);
    const best = ents.length ? ents.reduce((a, b) => (b.viaScore < a.viaScore ? b : a)) : null;
    assets.push({
      id: item.id, src: raw(item, 'src'), priority: Number(raw(item, 'priority') || 3), entities: ents.length,
      viaScore: best ? best.viaScore : null, angle: best ? best.angle : null, inFrustum: best ? best.inFrustum : null
    });
  }
  const ranked = assets.filter((a) => a.viaScore !== null).sort((a, b) => a.viaScore - b.viaScore);
  ranked.forEach((a, i) => { a.viaRank = i + 1; });

  return {
    camera: {
      position: camPos.toArray(), direction: camDir.toArray(), fov: cam.fov, aspect: cam.aspect, near: cam.near, far: cam.far
    },
    viewport: [window.innerWidth, window.innerHeight],
    assets,
    entities,
    viaOrder: ranked.map((a) => a.id)
  };
}

async function main () {
  const opts = parseArgs(process.argv.slice(2), DEFAULTS);
  const apps = opts.apps.split(',');
  const pages = loadPages().filter((p) => p.set === 'main' && p.config === 'baseline' && apps.includes(p.app));
  const outDir = opts.out ? path.resolve(opts.out) : path.join(EXP_DIR, 'probe');
  fs.mkdirSync(outDir, { recursive: true });

  const server = await startServer(opts.port);
  const browser = await openBrowser({ target: 'desktop', chrome: opts.chrome, headful: opts.headful, viewport: opts.viewport });
  try {
    for (const page of pages) {
      const tab = await browser.newPage();
      await tab.goto(`http://localhost:${opts.port}${page.url}`, { waitUntil: 'load' });
      await tab.waitForFunction(
        (app) => window.__exp && window.__exp.ready && (app !== 'tale' || (window.gameHTMLFile && window.gameHTMLFile.environment)),
        { timeout: 120000 }, page.app);
      await sleep(opts.settle * 1000);
      await tab.click('#ttff-start-button');
      await tab.waitForFunction(() => window.__exp.done, { timeout: 300000 });
      const result = await tab.evaluate(inspectScene);
      await tab.close();
      const out = { app: page.app, probedAt: new Date().toISOString(), emulatedViewport: viewportFromString(opts.viewport), ...result };
      fs.writeFileSync(path.join(outDir, `${page.app}.json`), JSON.stringify(out, null, 2) + '\n');
      const inView = result.assets.filter((a) => a.inFrustum).map((a) => `${a.id}(P${a.priority})`);
      console.log(`[probe] ${page.app}: ${result.entities.length} entities, ${result.viaOrder.length} ranked assets; in initial frustum: ${inView.join(', ')}`);
    }
  } finally {
    await closeBrowser(browser, 'desktop');
    server.close();
  }
}

main().catch((err) => { console.error(err); process.exit(1); });
